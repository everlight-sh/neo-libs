"""Generates src/entities.neo from the WHATWG named character reference table.

    curl -sSO https://html.spec.whatwg.org/entities.json
    python3 tools/entities.py entities.json > src/entities.neo
"""
import json
import sys


def literal(data: bytes) -> str:
    out = []
    for b in data:
        if 32 <= b < 127 and b not in (34, 39, 92):
            out.append(chr(b))
        else:
            out.append(f"\\x{b:02x}")
    return '"' + "".join(out) + '"'


def main(path: str) -> None:
    table = json.load(open(path, encoding="utf-8"))
    entries = sorted((name[1:].encode("ascii"), value["characters"].encode("utf-8")) for name, value in table.items())
    names, values, index = bytearray(), bytearray(), bytearray()
    for name, value in entries + [(b"", b"")]:
        assert len(names) < 65536 and len(values) < 65536
        index += len(names).to_bytes(2, "little") + len(values).to_bytes(2, "little")
        names += name
        values += value
    print("; Generated by tools/entities.py from https://html.spec.whatwg.org/entities.json; do not edit.")
    print(f"; {len(entries)} named character references sorted bytewise by name (legacy names appear")
    print("; with and without the semicolon). The index holds, per entry and one sentinel, the name's")
    print("; and the value's start offsets as little-endian u16 pairs.")
    print(f"fn html_entity_count() -> i64 = {len(entries)}")
    print(f"fn html_entity_names() -> Arr u8 _ = {literal(bytes(names))}")
    print(f"fn html_entity_values() -> Arr u8 _ = {literal(bytes(values))}")
    print(f"fn html_entity_index() -> Arr u8 _ = {literal(bytes(index))}")


if __name__ == "__main__":
    main(sys.argv[1])
